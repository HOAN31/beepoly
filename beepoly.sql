-- ============================================================================
-- 2. Unicode NFC normalisation
-- ----------------------------------------------------------------------------
-- Vietnamese text stored in NFD (decomposed) breaks UNIQUE constraints, "="
-- comparison and ILIKE search — two visually identical strings both insert
-- successfully. The PDF import path (bo_the_tu_vung.source_pdf_url) is a
-- realistic source of NFD data. PostgreSQL has no built-in NFC CHECK, so this
-- normalises on write via trigger. Application code should still call the
-- same normalisation before INSERT/UPDATE.
-- Requires PostgreSQL 13+ (normalize()).
-- ============================================================================
CREATE OR REPLACE FUNCTION fn_normalize_nfc() RETURNS trigger AS $$
DECLARE
  col TEXT;
  val TEXT;
BEGIN
  FOR col IN
    SELECT attname
      FROM pg_attribute
     WHERE attrelid = TG_RELID
       AND attnum > 0
       AND NOT attisdropped
       AND atttypid IN ('text'::regtype, 'varchar'::regtype, 'bpchar'::regtype)
  LOOP
    val := to_jsonb(NEW) ->> col;
    IF val IS NOT NULL THEN
      NEW := jsonb_populate_record(NEW, jsonb_build_object(col, normalize(val, NFC)));
    END IF;
  END LOOP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

