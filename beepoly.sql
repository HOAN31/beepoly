-- A multiple-choice question must have exactly one correct option.
-- A plain CHECK cannot express "count across rows", so this is a deferred
-- constraint trigger (deferrable so a transaction can insert several options
-- before validating).
CREATE OR REPLACE FUNCTION fn_lua_chon_dap_an_dung() RETURNS trigger AS $$
DECLARE
  n INTEGER;
BEGIN
  SELECT count(*) INTO n
    FROM lua_chon_cau_hoi
   WHERE cau_hoi_id = COALESCE(NEW.cau_hoi_id, OLD.cau_hoi_id)
     AND la_dap_an_dung;

  IF n <> 1 THEN
    RAISE EXCEPTION
      'cau_hoi % must have exactly one correct option (found %)',
      COALESCE(NEW.cau_hoi_id, OLD.cau_hoi_id), n;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_lua_chon_dap_an_dung
  AFTER INSERT OR UPDATE OR DELETE ON lua_chon_cau_hoi
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION fn_lua_chon_dap_an_dung();

CREATE TRIGGER trg_nguoi_dung_nfc  BEFORE INSERT OR UPDATE ON nguoi_dung
  FOR EACH ROW EXECUTE FUNCTION fn_normalize_nfc();
