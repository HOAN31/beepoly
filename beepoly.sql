  FOR EACH ROW EXECUTE FUNCTION fn_normalize_nfc();
CREATE TRIGGER trg_goi_dich_vu_nfc BEFORE INSERT OR UPDATE ON goi_dich_vu
  FOR EACH ROW EXECUTE FUNCTION fn_normalize_nfc();

